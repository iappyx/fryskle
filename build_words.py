#!/usr/bin/env python3
"""Build words.js for Fryskle: the daily words and valid guesses for each mode
(4, 5, 6 and 7 letters).

Usage:
  # Shuffle an answer list ONCE, before launch (edits the file in place):
  python build_words.py shuffle answers.txt

  # Build words.js from the word lists + the answer lists:
  python build_words.py build

Per mode, the build reads:
  - the word list (valid guesses): wordlist/fy_NL-4.txt to -7.txt,
    made with make_wordlist.py; one word per line
  - the answer list (one word per day): answers.txt (5 letters),
    answers-4.txt, answers-6.txt and answers-7.txt
A mode without an answer list is left out of the game.

After launch, only ADD new answers at the END of an answer list. Reordering or
removing answers changes the puzzle for days that are already fixed.
"""
import argparse
import json
import os
import random
import sys
import unicodedata

LENGTHS = (4, 5, 6, 7)
ANSWER_FILES = {4: "answers-4.txt", 5: "answers.txt", 6: "answers-6.txt", 7: "answers-7.txt"}
WORDLIST = os.path.join("wordlist", "fy_NL-{n}.txt")
ALLOWED = set("abcdefghijklmnopqrstuvwxyzâêéôûú")
STRICT_THRESHOLD = 500  # below this many guess words, accept any guess of the right length


def norm(word):
    return unicodedata.normalize("NFC", word).strip().lower()


def valid(word, n=None):
    return (len(word) == n if n else len(word) in LENGTHS) and all(ch in ALLOWED for ch in word)


def read_lines(path):
    with open(path, encoding="utf-8") as f:
        return f.read().splitlines()


def read_wordlist(path, n):
    words = set()
    for i, line in enumerate(read_lines(path)):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if i == 0 and line.isdigit():  # Hunspell .dic count line
            continue
        word = norm(line.split("/")[0].split()[0])
        if valid(word, n):
            words.add(word)
    return words


def read_answers(path, n=None):
    seen, answers = set(), []
    for line in read_lines(path):
        word = norm(line)
        if not word or word.startswith("#"):
            continue
        if not valid(word, n):
            print(f"  skipped answer (wrong length or letters): {word}", file=sys.stderr)
            continue
        if word in seen:
            print(f"  skipped duplicate answer: {word}", file=sys.stderr)
            continue
        seen.add(word)
        answers.append(word)
    return answers


def cmd_shuffle(args):
    answers = read_answers(args.file)
    random.Random(args.seed).shuffle(answers)
    with open(args.file, "w", encoding="utf-8") as f:
        f.write("\n".join(answers) + "\n")
    print(f"Shuffled {len(answers)} answers in {args.file}")


def cmd_build(args):
    modes = {}
    for n in LENGTHS:
        if not os.path.exists(ANSWER_FILES[n]):
            print(f"{n} letters: no {ANSWER_FILES[n]}, mode left out")
            continue
        answers = read_answers(ANSWER_FILES[n], n)
        wl = WORDLIST.format(n=n)
        guesses = read_wordlist(wl, n) if os.path.exists(wl) else set()

        missing = [w for w in answers if guesses and w not in guesses]
        if missing:
            print(f"Warning: {len(missing)} {n}-letter answers are not in {wl}:", file=sys.stderr)
            print("  " + ", ".join(missing), file=sys.stderr)

        # Answers are always valid guesses; the game merges them in, so leave them out here.
        guess_only = sorted(guesses - set(answers))
        strict = len(guesses | set(answers)) >= STRICT_THRESHOLD
        modes[str(n)] = {"answers": answers, "guesses": guess_only, "strict": strict}
        print(f"{n} letters: {len(answers)} answers ({len(answers)} days), "
              f"{len(guess_only)} extra guess words, strict={strict}")

    config = {"start": args.start}
    out = (
        "// Generated by build_words.py. Edit the answer lists and rebuild instead of editing this file.\n"
        "// Words from the Foarkarswurdlist (c) Fryske Akademy, GNU GPL v3: see wordlist/README.txt and wordlist/gpl.txt\n"
        f"window.FRYSKLE_CONFIG = {json.dumps(config)};\n"
        f"window.FRYSKLE_MODES = {json.dumps(modes, ensure_ascii=False)};\n"
    )
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"Wrote {args.out}")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("shuffle", help="shuffle an answer file in place (do this once, before launch)")
    s.add_argument("file")
    s.add_argument("--seed", type=int, default=1)
    s.set_defaults(func=cmd_shuffle)

    b = sub.add_parser("build", help="generate words.js")
    b.add_argument("--out", default="words.js")
    b.add_argument("--start", default="2026-09-26", help="date of puzzle #1 (YYYY-MM-DD), the same for all modes")
    b.set_defaults(func=cmd_build)

    args = p.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
